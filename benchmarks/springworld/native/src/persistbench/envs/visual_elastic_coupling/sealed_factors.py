"""Committed counterfactual donors for the evaluator-private sealed bank.

The physical implementation is the same as the development intervention.
The separate entry binds the exact planned source, retains every failed
attempt, and checks all generated bytes independently before admitting them.
"""
import argparse,hashlib,json,multiprocessing,os,time
from concurrent.futures import ProcessPoolExecutor,as_completed
from importlib.metadata import version
from pathlib import Path,PurePosixPath
import numpy as np
from .specificity_bank import changed_parameters,VARIANTS,LOW,HIGH
from .sealed_bank import SealedBank
from .dataset_snapshot import stable_digest,checked_asset,content_digest
from .schema import Episode,history_payload

SCHEMA='vec.sealed-factor-admission.v1'
METADATA=('SPECIFICITY_CONFIG.json','SPECIFICITY_REPORT.json','MANIFEST.private.json')
INTERVENTION=dict(schema='vec.factor-intervention.v1',frames=96,source_role='forced',
    variants={k:list(v) for k,v in VARIANTS.items()},lower=LOW.tolist(),upper=HIGH.tolist(),
    change_rule='half_range_toward_opposite_half',preserve=['initial_state','applied_actions','renderer','query','target'])


def planned_sources(bank):
    if not isinstance(bank,SealedBank) or bank.closed:raise PermissionError('open authorized sealed base bank required')
    bank.verify_content()
    spec=bank.authorization.protocol['assays']['factor_specificity']
    if spec.get('donor_intervention')!=INTERVENTION:raise ValueError('factor intervention not frozen exactly')
    profiles=spec['profiles']
    if not isinstance(profiles,dict):raise ValueError('named factor profiles required')
    strata={p['stratum'] for p in profiles.values()};slots={}
    for row in bank.rows.values():
        slot=(row['stratum'],row['system_key'],row['kind'],row['replicate'])
        if slot in slots:raise ValueError('duplicate source slot')
        slots[slot]=row
    sources={}
    for stratum in sorted(strata):
        if stratum not in bank.plans:raise ValueError('unregistered factor population')
        for case in bank.plans[stratum]['plan']['cases']:
            index=case['episode_slots']['forced'][0]
            row=slots[(stratum,case['system_key'],'forced',index)]
            key=(case['system_key'],case['replicate'])
            if key in sources:raise ValueError('factor case identity collision')
            # This is a declared support check, never a score or recovery filter.
            # Failure aborts the attempt; no alternate source is substituted.
            if row['raw_frames']<96:raise ValueError('planned source lacks observed factor support; no resampling')
            for variant in VARIANTS:changed_parameters(row['theta'],variant)
            sources[key]=row
    return sources


def capture_factor_content(root):
    root=Path(root);before={p:stable_digest(checked_asset(root,p)) for p in METADATA}
    rows=json.loads((root/'MANIFEST.private.json').read_text())['episodes'];paths=set(METADATA)
    for row in rows:
        for name in [row['private_state_path'],str(PurePosixPath(row['private_state_path']).with_name('private.json'))]+[a['path'] for a in row['assets'].values()]:
            if name in paths:raise ValueError('factor asset reused across declared slots')
            paths.add(name)
    files=[dict(path=p,**stable_digest(checked_asset(root,p))) for p in sorted(paths)]
    if before!={p:stable_digest(checked_asset(root,p)) for p in METADATA}:raise ValueError('factor metadata changed during verification')
    return dict(files=files,content_sha256=content_digest(files),episodes=len(rows))


def validate_rows(root,bank,sources):
    root=Path(root);config=json.loads((root/'SPECIFICITY_CONFIG.json').read_text());report=json.loads((root/'SPECIFICITY_REPORT.json').read_text())
    rows=json.loads((root/'MANIFEST.private.json').read_text())['episodes']
    expected=dict(protocol_sha256=bank.authorization.protocol_sha256,selection_sha256=bank.authorization.selection_sha256,
        base_admission_sha256=bank.admission_sha256,base_manifest_sha256=bank.manifest_sha256,intervention=INTERVENTION)
    if config.get('schema')!='vec.sealed-factor-bank.v1' or any(config.get(k)!=v for k,v in expected.items()):raise ValueError('factor source/protocol binding differs')
    if report.get('execution_errors')!=[] or report.get('episodes')!=len(rows) or len(rows)!=len(sources)*len(VARIANTS):raise ValueError('factor generation is incomplete')
    seen=set();episode_keys=set()
    for row in rows:
        identity=(row['query_system_key'],row['replicate'],row['variant']);key=identity[:2];variant=identity[2]
        if identity in seen or key not in sources or variant not in VARIANTS:raise ValueError('factor family or source differs')
        source=sources[key];seen.add(identity)
        episode_key=hashlib.sha256((source['episode_key']+':'+variant+':factor-intervention-v1').encode()).hexdigest()[:32]
        bindings=dict(episode_key=episode_key,source_episode_key=source['episode_key'],query_system_key=source['system_key'],
            split='test',stratum=source['stratum'],query_theta=source['theta'],
            donor_theta=changed_parameters(source['theta'],variant).tolist(),changed_factors=list(VARIANTS[variant]),requested_frames=96)
        if any(row.get(k)!=v for k,v in bindings.items()):raise ValueError('factor row differs from exact planned intervention')
        if row['episode_key'] in episode_keys or row['episode_key'] in bank.rows:raise ValueError('factor episode identity reused')
        episode_keys.add(row['episode_key'])
        if not 1<=row['raw_frames']<=96 or (row['raw_frames']!=96 and not row.get('failure')):raise ValueError('invalid factor failure/support declaration')
    return rows


def audit_assets(root,bank,rows):
    """Independent state/action/pixel checks, retaining physical short prefixes."""
    root=Path(root);out=[]
    for row in rows:
        source=bank.rows[row['source_episode_key']];n=row['raw_frames'];issues=[]
        with np.load(checked_asset(root,row['private_state_path']),allow_pickle=False) as d:states=d['state']
        with np.load(bank._path(source['private_state_path']),allow_pickle=False) as d:original=d['state'][:n]
        if states.shape!=(n,8) or not np.isfinite(states).all():raise ValueError('factor private state shape/finiteness differs')
        if not np.array_equal(states[0],original[0]):issues.append('changed_initial_state')
        center=float(np.max(np.abs((states[:,:2]+states[:,2:4]-original[:,:2]-original[:,2:4])/2)))
        if row['variant']=='k_only' and center>1e-8:issues.append('irrelevant_k_center_invariant')
        if set(row['assets'])!=set(source['assets']):issues.append('resolution_support')
        for resolution,asset in row['assets'].items():
            path=checked_asset(root,asset['path']);actual=stable_digest(path)
            if any(actual[k]!=asset[k] for k in ('bytes','sha256')):issues.append('visible_digest')
            with np.load(path,allow_pickle=False) as d:images=d['images'];actions=d['actions'];times=d['timestamps']
            with np.load(bank._path(source['assets'][resolution]['path']),allow_pickle=False) as d:
                initial=d['images'][0];original_actions=d['actions'][:95]
            if images.dtype!=np.uint8 or images.shape!=(n,int(resolution),int(resolution)):issues.append('visible_shape')
            if not np.array_equal(images[0],initial):issues.append('changed_initial_pixels')
            if not np.array_equal(actions,original_actions[:n-1]):issues.append('changed_actions')
            if times.shape!=(n,) or not np.allclose(times,np.arange(n)*.05,atol=1e-12,rtol=0):issues.append('time_support')
            if hashlib.sha256(original_actions.tobytes()).hexdigest()!=row['action_sha256']:issues.append('full_action_commitment')
        out.append(dict(episode_key=row['episode_key'],issues=issues,raw_frames=n,physical_failure=row.get('failure'),center_difference_m=center))
    return dict(status='FAIL' if any(r['issues'] for r in out) else 'PASS',cases=out,
        scope='exact source/factor and causal asset integrity including failed prefixes; not method specificity or sufficient assay support')


class SealedFactorBank:
    def __init__(self,root,bank,*,admission_path,admission_sha256):
        sources=planned_sources(bank);self.root=Path(root);self.bank=bank;self.closed=False
        self.admission_path=Path(admission_path);self.admission_sha256=admission_sha256
        if stable_digest(self.admission_path)['sha256']!=admission_sha256:raise ValueError('factor admission commitment differs')
        self.admission=json.loads(self.admission_path.read_text())
        if self.admission.get('schema')!=SCHEMA or self.admission.get('status')!='PASS' or self.admission.get('base_admission_sha256')!=bank.admission_sha256:
            raise ValueError('sealed factor admission is missing or refers to another base')
        if capture_factor_content(self.root)!=self.admission.get('content'):raise ValueError('factor data bytes differ')
        rows=validate_rows(self.root,bank,sources)
        actual_audit=audit_assets(self.root,bank,rows)
        if actual_audit['status']!='PASS' or actual_audit!=self.admission.get('asset_audit'):raise ValueError('independent factor asset audit differs')
        self.cases={}
        for row in rows:self.cases.setdefault((row['query_system_key'],row['replicate']),{})[row['variant']]=row
        self.manifest_sha256=stable_digest(self.root/'MANIFEST.private.json')['sha256']
        self._files={f['path']:f for f in self.admission['content']['files']}
        bank._audit('OPEN_FACTOR_BANK',admission_sha256=admission_sha256,episodes=len(rows))

    def histories(self,key,replicate,resolution):
        if self.closed or self.bank.closed:raise PermissionError('factor bank closed')
        if key[0]!='test' or resolution!=self.bank.resolution:raise ValueError('factor observation profile differs')
        rows=self.cases[(key[1],replicate)];histories={};metadata={}
        for variant,row in rows.items():
            if row['raw_frames']<96:raise ValueError('factor observed support unavailable; retain case failure')
            asset=row['assets'][str(resolution)];path=checked_asset(self.root,asset['path']);actual=stable_digest(path)
            if any(actual[k]!=self._files[asset['path']][k] for k in ('bytes','sha256')):raise ValueError('factor public asset changed during evaluation')
            with np.load(path,allow_pickle=False) as d:images=d['images'];actions=d['actions'];times=d['timestamps']
            ep=Episode(images,actions,times,np.zeros((len(images),8)),{})
            name='factor_'+variant;histories[name]=[history_payload(ep,0,95)]
            metadata[name]=dict(donor_episode_keys=[row['episode_key']],processed_frames=96,unique_frames=96,unique_transitions=95,
                episodes=1,effort_n2_s=float(np.sum(actions[:95]**2)*.05))
            self.bank._audit('READ_FACTOR_PUBLIC',episode_key=row['episode_key'],resolution=resolution)
        return next(iter(rows.values()))['source_episode_key'],histories,metadata

    def close(self):
        if self.closed:return
        try:
            if self.bank.closed:raise ValueError('factor verification must precede closing the base bank')
            self.bank.authorization.revalidate()
            if stable_digest(self.admission_path)['sha256']!=self.admission_sha256 or capture_factor_content(self.root)!=self.admission['content']:
                raise ValueError('factor inputs changed before completion')
            self.bank._audit('CLOSE_FACTOR_BANK',status='PASS',admission_sha256=self.admission_sha256)
        except Exception as exc:
            if not self.bank.closed:self.bank._audit('CLOSE_FACTOR_BANK',status='FAIL',error=repr(exc))
            raise
        finally:self.closed=True

    def __enter__(self):return self
    def __exit__(self,*_):self.close()


def generate_factors(output,bank,*,workers=32):
    sources=planned_sources(bank);output=Path(output)
    if not isinstance(workers,int) or workers<1:raise ValueError('positive factor worker budget required')
    runtime=bank.authorization.protocol['render_runtime']
    if version('mujoco')!=runtime['mujoco_version'] or os.environ.get('MUJOCO_GL')!=runtime['backend']:raise ValueError('factor render runtime differs')
    if output.exists():raise ValueError('factor attempt exists; do not overwrite or resample')
    output.mkdir(parents=True);began=time.monotonic()
    config=dict(schema='vec.sealed-factor-bank.v1',protocol_sha256=bank.authorization.protocol_sha256,selection_sha256=bank.authorization.selection_sha256,
        base_admission_sha256=bank.admission_sha256,base_manifest_sha256=bank.manifest_sha256,intervention=INTERVENTION)
    (output/'SPECIFICITY_CONFIG.json').write_text(json.dumps(config,indent=2)+'\n')
    from .specificity_bank import generate_case
    jobs=[(str(bank.root),str(output),source,rep,variant) for (system,rep),source in sources.items() for variant in VARIANTS]
    rows=[];errors=[]
    with ProcessPoolExecutor(max_workers=workers,mp_context=multiprocessing.get_context('spawn')) as pool:
        futures={pool.submit(generate_case,j):(j[2]['episode_key'],j[3],j[4]) for j in jobs}
        for future in as_completed(futures):
            try:rows.append(future.result())
            except Exception as exc:errors.append(dict(case=futures[future],error=repr(exc)))
            if (len(rows)+len(errors))%128==0:print(json.dumps(dict(completed=len(rows)+len(errors),total=len(jobs),errors=len(errors))),flush=True)
    rows.sort(key=lambda r:r['episode_key'])
    (output/'MANIFEST.private.json').write_text(json.dumps(dict(episodes=rows),indent=2)+'\n')
    report=dict(episodes=len(rows),execution_errors=errors,physical_failures=[r['episode_key'] for r in rows if r['failure']],seconds=time.monotonic()-began)
    (output/'SPECIFICITY_REPORT.json').write_text(json.dumps(report,indent=2)+'\n')
    if errors:raise RuntimeError('factor execution failures retained; no admission')
    validate_rows(output,bank,sources);asset_audit=audit_assets(output,bank,rows)
    if asset_audit['status']!='PASS':
        (output/'FAILED_AUDIT.json').write_text(json.dumps(asset_audit,indent=2)+'\n');raise ValueError('factor asset contract failed')
    bank.verify_content()
    content=capture_factor_content(output)
    admission=dict(schema=SCHEMA,status='PASS',base_admission_sha256=bank.admission_sha256,content=content,asset_audit=asset_audit)
    path=output/'FACTOR_ADMISSION.json';path.write_text(json.dumps(admission,indent=2)+'\n')
    return dict(admission_sha256=stable_digest(path)['sha256'],content_sha256=content['content_sha256'],episodes=len(rows),physical_failures=len(report['physical_failures']))


def main():
    from .sealed_access import SealedAuthorization
    p=argparse.ArgumentParser()
    for name in ('protocol','selection','bank','admission','output'):p.add_argument('--'+name,type=Path,required=True)
    for name in ('protocol-sha256','selection-sha256','admission-sha256'):p.add_argument('--'+name,required=True)
    p.add_argument('--workers',type=int,default=32);a=p.parse_args()
    authorization=SealedAuthorization(a.protocol,a.selection,protocol_sha256=a.protocol_sha256,selection_sha256=a.selection_sha256)
    with SealedBank(a.bank,authorization,admission_path=a.admission,admission_sha256=a.admission_sha256,audit_path=a.output.parent/(a.output.name+'.access.private.jsonl')) as bank:
        result=generate_factors(a.output,bank,workers=a.workers)
    print(json.dumps(result),flush=True)


if __name__=='__main__':main()
